"""Aggregate-specific contracts with plain Python DTOs at every boundary."""

from typing import Protocol
from pharmacy.domain.core import Order, OrderDraft


class OrderRepository(Protocol):
    def get(self, order_id: int, lock: bool = False) -> Order: ...
    def create(
        self, draft: OrderDraft, payment_method: str, recipient: dict
    ) -> Order: ...
    def save(self, order: Order) -> None: ...
    def product_ids(self, order_id: int) -> list[int]: ...
    def prescription_required(self, order_id: int) -> bool: ...
    def verify_prescription(
        self, order_id: int, actor_id: int, approved: bool
    ) -> None: ...
    def prescription_approved(self, order_id: int) -> bool: ...


class InventoryRepository(Protocol):
    def offer(self, pharmacy_id: int, product_id: int, lock: bool = False) -> dict: ...
    def reserve(self, order_id: int) -> None: ...
    def release(self, order_id: int, consume: bool = False) -> None: ...
    def change(
        self, actor_id: int, pharmacy_id: int, product_id: int, changes: dict
    ) -> dict: ...


class PaymentRepository(Protocol):
    def request(self, order: Order, key: str, provider: str) -> dict: ...
    def get(self, payment_id: int) -> dict: ...
    def get_refund(self, refund_id: int) -> dict: ...
    def captured(self, order_id: int) -> list[dict]: ...
    def refundable(self, payment_id: int): ...
    def cancel_pending(self, order_id: int) -> None: ...
    def settle(self, payment_id: int, result: dict) -> None: ...
    def paid(self, order_id: int) -> bool: ...
    def refund(self, order: Order, amount, reason: str) -> dict: ...
    def settle_refund(self, refund_id: int, result: dict) -> None: ...


class LoyaltyRepository(Protocol):
    def policies(self, customer_id: int, promotion: str | None) -> list: ...
    def balance(self, customer_id: int, lock: bool = False) -> int: ...
    def redeem(self, order: Order, points: int) -> None: ...
    def restore_redeemed(self, order: Order) -> None: ...
    def calculate_points(self, order: Order) -> int: ...
    def accrue(self, order: Order, points: int | None = None) -> None: ...
    def reverse(self, order: Order) -> None: ...


class DeliveryRepository(Protocol):
    def allowed(self, method: str, offer: dict) -> bool: ...
    def update(
        self, order_id: int, status: str, tracking: str | None = None
    ) -> None: ...


class OutboxRepository(Protocol):
    def add(
        self, event_type: str, payload: dict, event_id: str | None = None
    ) -> str: ...
    def find(self, event_id: str) -> dict | None: ...


class EngagementRepository(Protocol):
    def notify_promotion(self, promotion_id: int) -> None: ...
    def notify_order(self, order: Order) -> None: ...
    def notify_availability(self, product_id: int, pharmacy_id: int) -> None: ...
    def save_personal(self, customer_id: int, kind: str, data: dict) -> dict: ...


class CartRepository(Protocol):
    def set_item(self, customer_id: int, product_id: int, quantity: int, allow_unavailable: bool = False) -> dict: ...


class PaymentGateway(Protocol):
    def authorize(self, reference: str, amount, idempotency_key: str) -> dict: ...
    def refund(self, reference: str, amount, idempotency_key: str) -> dict: ...


class ShipmentProvider(Protocol):
    def prepare(self, order_id: int, method: str) -> str: ...


class UnitOfWork(Protocol):
    orders: OrderRepository
    inventory: InventoryRepository
    payments: PaymentRepository
    loyalty: LoyaltyRepository
    delivery: DeliveryRepository
    outbox: OutboxRepository
    engagement: EngagementRepository
    carts: CartRepository

    def __enter__(self): ...
    def __exit__(self, exc_type, exc, tb): ...
    def commit(self): ...
    def rollback(self): ...
    def audit(
        self, actor_id: int | None, action: str, target_id: int, details: dict
    ): ...
